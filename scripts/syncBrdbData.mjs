// Union: crate list first (stable order), then dump-only assets sorted.
const union = (crateList, dumpList) => {
  const seen = new Set(crateList);
  return [...crateList, ...dumpList.filter(n => !seen.has(n)).sort()];
};
const basic = union(crateBasic, inventory.allBrickAssets);
const procedural = union(
  crateProcedural,
  inventory.proceduralBrickAssets ?? []
);
if (basic.length < 240 || procedural.length < 30)
  throw new Error(
    `catalog extraction failed (basic=${basic.length}, procedural=${procedural.length}); check assets/bricks.rs and data/componentInventory.json`
  );
let cat = '// GENERATED by scripts/syncBrdbData.mjs. Do not edit by hand.\n';
cat += '// Regenerate with: just sync-brdb-data\n\n';
cat += `export const BASIC_BRICK_ASSETS: readonly string[] = ${JSON.stringify(
  basic,
  null,
  2
)};\n\n`;
cat += `export const PROCEDURAL_BRICK_ASSETS: readonly string[] = ${JSON.stringify(
  procedural,
  null,
  2
)};\n\n`;
cat += `/** Every known brick asset name (basic + procedural), self-keyed for
 * typo-safe references with editor completion, e.g.
 * \`BRICK_ASSETS.B_1x1_Gate_MicrochipInput\`. */
export const BRICK_ASSETS = {
${[...basic, ...procedural]
  .sort()
  .map(n => `  ${n}: '${n}',`)
  .join('\n')}
} as const;

`;
cat += `const BASIC = new Set(BASIC_BRICK_ASSETS);
const PROCEDURAL = new Set(PROCEDURAL_BRICK_ASSETS);

/** Classify a brick asset as procedural (parametric, carries a size) or basic. */
export function isProceduralAsset(name: string): boolean {
  if (PROCEDURAL.has(name)) return true;
  if (BASIC.has(name)) return false;
  // Fallback for assets not in the catalog: PB_*/BP_* families are procedural.
  return name.startsWith('PB_') || name.startsWith('BP_');
}
`;
writeFileSync('src/brdb/catalog.ts', cat);

// --- componentDb.ts ---
// component_db.rs is autogenerated in the crate from a game dump; extract
// the component type->data-struct pairs, the wire port registry, and the
// entity type->class pairs.
function componentTables(dbRs) {
  const extractPairs = tableName => {
    const m = dbRs.match(
      new RegExp(
        String.raw`pub static ${tableName}: &\[\(&str, &str\)\] = &\[([\s\S]*?)\n\];`
      )
    );
    if (!m) throw new Error(`component_db.rs: table ${tableName} not found`);
    return [...m[1].matchAll(/\("([^"]+)", "([^"]+)"\)/g)].map(p => [
      p[1],
      p[2],
    ]);
  };
  const extractStrings = tableName => {
    const m = dbRs.match(
      new RegExp(
        String.raw`pub static ${tableName}: &\[&str\] = &\[([\s\S]*?)\n\];`
      )
    );
    if (!m) throw new Error(`component_db.rs: table ${tableName} not found`);
    return [...m[1].matchAll(/"([^"]+)"/g)].map(p => p[1]);
  };

  const componentPairs = extractPairs('COMPONENT_TYPE_STRUCT_PAIRS');
  const wirePorts = extractStrings('WIRE_PORT_NAMES');
  const entityPairs = extractPairs('ENTITY_TYPE_STRUCT_PAIRS');
  if (
    componentPairs.length < 50 ||
    wirePorts.length < 100 ||
    !entityPairs.length
  )
    throw new Error(
      `component_db extraction failed (components=${componentPairs.length}, ports=${wirePorts.length}, entities=${entityPairs.length})`
    );

  // STRUCT_DEFAULTS: component data struct -> game-default field values. The values are Rust
  // expressions; parse them with a small balanced-delimiter parser. Struct-typed defaults are
  // emitted as `NestedStructDefault(vec![("X", Box::new(..)), ..])` (e.g. Vector2D {X,Y},
  // LinearColor {R,G,B,A}) and become nested JS objects, which a plain regex cannot handle.
  const defaultsStart = dbRs.indexOf('pub static STRUCT_DEFAULTS');
  if (defaultsStart < 0)
    throw new Error('component_db.rs: STRUCT_DEFAULTS not found');
  const structDefaults = {};
  {
    const src = dbRs.slice(defaultsStart);
    let i = src.indexOf('vec!['); // the outer defaults vec
    if (i < 0)
      throw new Error('component_db.rs: STRUCT_DEFAULTS vec not found');
    i += 'vec!['.length;
    const at = tok => src.startsWith(tok, i);
    const ws = () => {
      while (i < src.length && /\s/.test(src[i])) i++;
    };
    const eat = tok => {
      ws();
      if (at(tok)) {
        i += tok.length;
        return true;
      }
      return false;
    };
    const expect = tok => {
      if (!eat(tok))
        throw new Error(
          `STRUCT_DEFAULTS: expected '${tok}' near: ${src.slice(i, i + 60)}`
        );
    };
    const parseString = () => {
      ws();
      if (src[i] !== '"')
        throw new Error(
          `STRUCT_DEFAULTS: expected string near: ${src.slice(i, i + 40)}`
        );
      i++;
      let out = '';
      while (i < src.length && src[i] !== '"') {
        if (src[i] === '\\') {
          out += src[i + 1];
          i += 2;
        } else out += src[i++];
      }
      i++; // closing quote
      return out;
    };
    // Parse a `("name", <value>), ...` list terminated by ']', invoking onPair for each.
    const parsePairs = onPair => {
      ws();
      while (!eat(']')) {
        expect('(');
        const name = parseString();
        expect(',');
        const val = parseValue();
        expect(')');
        eat(',');
        onPair(name, val);
        ws();
      }
    };
    // `(<value>)` after a tuple-variant name.
    const parseArg = () => {
      const v = parseValue();
      expect(')');
      return v;
    };
    const parseValue = () => {
      ws();
      if (eat('Box::new(')) {
        const v = parseValue();
        expect(')');
        ws();
        if (at('as Box<')) i = src.indexOf('>', i) + 1; // strip ` as Box<dyn AsBrdbValue>`
        return v;
      }
      if (eat('NestedStructDefault(')) {
        expect('vec![');
        const obj = {};
        parsePairs((k, v) => (obj[k] = v));
        expect(')');
        return obj;
      }
      if (eat('SavedBrickColor')) {
        expect('{');
        const c = {};
        while (!eat('}')) {
          ws();
          const key = src[i++]; // r/g/b/a
          expect(':');
          ws();
          const m = /^-?\d+/.exec(src.slice(i));
          c[key.toUpperCase()] = Number(m[0]);
          i += m[0].length;
          eat(',');
        }
        return { B: c.B, G: c.G, R: c.R, A: c.A }; // embedded Color field order
      }
      if (eat('String::from(')) {
        const s = parseString();
        expect(')');
        return s;
      }
      // Dynamic containers and enums: { $elementType, $array } /
      // { $keyType, $valueType, $map } / { $enum, value }.
      if (eat('BrdbDynamicArray::empty(')) {
        const $elementType = parseString();
        expect(')');
        return { $elementType, $array: [] };
      }
      if (eat('BrdbDynamicMap::empty(')) {
        const $keyType = parseString();
        expect(',');
        const $valueType = parseString();
        expect(')');
        return { $keyType, $valueType, $map: [] };
      }
      if (eat('BrdbDynamicEnum::new(')) {
        const $enum = parseString();
        expect(',');
        const value = parseValue();
        expect(')');
        return { $enum, value };
      }
      // Wire values: { $variant, value } with the alternative's type name.
      for (const [prefix, str, bool] of [
        ['WireValue::', 'Str', 'Bool'],
        ['EA3WireVariant::', 'str', 'bool'],
      ]) {
        if (!eat(prefix)) continue;
        const fields = keys => {
          expect('{');
          const obj = {};
          while (!eat('}')) {
            ws();
            const key = /^\w+/.exec(src.slice(i))[0];
            i += key.length;
            expect(':');
            obj[keys[key]] = parseValue();
            eat(',');
          }
          return obj;
        };
        const xyz = { x: 'X', y: 'Y', z: 'Z', w: 'W' };
        if (eat('Number(')) return { $variant: 'f64', value: parseArg() };
        if (eat('Int(')) return { $variant: 'i64', value: parseArg() };
        if (eat('Bool(')) return { $variant: bool, value: parseArg() };
        if (eat('Str(')) {
          const value = parseString();
          eat('.into()');
          expect(')');
          return { $variant: str, value };
        }
        if (eat('Enum('))
          return { $variant: 'dynamic_enum', value: parseArg() };
        if (eat('Object(')) {
          parseArg(); // EA3 asset index; defaults are null references
          return { $variant: 'weak_object', value: null };
        }
        if (eat('Object')) return { $variant: 'weak_object', value: null };
        // WireGraphExec is an empty struct alternative.
        if (eat('Exec')) return { $variant: 'WireGraphExec', value: {} };
        if (eat('Vector(Vector3f')) {
          const value = fields(xyz);
          expect(')');
          return { $variant: 'Vector', value };
        }
        if (eat('Vector')) return { $variant: 'Vector', value: fields(xyz) };
        if (eat('Quat')) return { $variant: 'Quat', value: fields(xyz) };
        if (eat('Rotator'))
          return {
            $variant: 'Rotator',
            value: fields({ pitch: 'Pitch', yaw: 'Yaw', roll: 'Roll' }),
          };
        if (eat('LinearColor'))
          return {
            $variant: 'LinearColor',
            value: fields({ r: 'R', g: 'G', b: 'B', a: 'A' }),
          };
        throw new Error(
          `STRUCT_DEFAULTS: unhandled wire value near: ${src.slice(i, i + 60)}`
        );
      }
      if (eat('true')) return true;
      if (eat('false')) return false;
      const m =
        /^-?\d+(?:\.\d+)?(?:[eE]-?\d+)?(?:f32|f64|[iu](?:8|16|32|64))?/.exec(
          src.slice(i)
        );
      if (m) {
        i += m[0].length;
        return Number(m[0].replace(/(?:f32|f64|[iu](?:8|16|32|64))$/, ''));
      }
      throw new Error(
        `STRUCT_DEFAULTS: unhandled value near: ${src.slice(i, i + 60)}`
      );
    };

    // Top level: `("StructName", vec![ <fields> ]), ...`
    ws();
    while (!eat(']')) {
      expect('(');
      const structName = parseString();
      expect(',');
      expect('vec![');
      const fields = {};
      parsePairs((k, v) => (fields[k] = v));
      expect(')');
      eat(',');
      structDefaults[structName] = fields;
      ws();
    }
  }
  if (Object.keys(structDefaults).length < 100)
    throw new Error(
      `STRUCT_DEFAULTS extraction failed (${
        Object.keys(structDefaults).length
      } structs)`
    );
  return { componentPairs, wirePorts, entityPairs, structDefaults };
}

function componentConstants(inventory) {
  // Per-component host bricks and wire port names, from the game dump.
  const componentPorts = {};
  for (const c of inventory.components)
    componentPorts[c.class] = {
      bricks: c.bricks,
      inputs: c.inputs,
      outputs: c.outputs,
    };
  if (Object.keys(componentPorts).length < 200)
    throw new Error(
      `inventory component extraction failed (${
        Object.keys(componentPorts).length
      })`
    );

  // COMPONENTS: ergonomic authoring constants, e.g.
  // COMPONENTS.PlayAudioAt.NAME / .BRICK / .PORTS.Exec
  // Keys keep the catalog's own casing (PlayAudioAt), minus the type-system
  // prefixes; port keys are the port names verbatim.
  const shortKey = cls =>
    cls
      .replace(/^BrickComponentType_/, '')
      .replace(/^BrickComponent_/, '')
      .replace(/^Component_/, '')
      .replace(/^WireGraphPseudo_/, '')
      .replace(/^WireGraph_/, '')
      .replace(/^Internal_/, '');
  // Some builds ship a public + an Internal_ variant that strip to the same
  // short key (e.g. AerodynamicSurface). Keep the Internal_ qualifier on the
  // internal one so the public component keeps the clean key.
  const shortKeyCounts = {};
  for (const c of inventory.components) {
    const k = shortKey(c.class);
    shortKeyCounts[k] = (shortKeyCounts[k] || 0) + 1;
  }
  const componentKey = cls => {
    const short = shortKey(cls);
    return shortKeyCounts[short] > 1 && /(?:^|_)Internal_/.test(cls)
      ? `Internal_${short}`
      : short;
  };
  const componentsConst = {};
  for (const c of inventory.components) {
    const key = componentKey(c.class);
    if (componentsConst[key])
      throw new Error(
        `COMPONENTS key collision: ${key} (${c.class} vs ${componentsConst[key].NAME})`
      );
    const ports = {};
    // '.' is not identifier-safe: 'InputA.X' keys as InputA_X
    for (const p of [...c.inputs, ...c.outputs])
      ports[p.replace(/\./g, '_')] = p;
    componentsConst[key] = {
      NAME: c.class,
      BRICK: c.bricks[0],
      BRICKS: c.bricks,
      PORTS: ports,
    };
  }
  return { componentPorts, componentsConst };
}

